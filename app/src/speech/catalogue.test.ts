// @vitest-environment node
import { createHash } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { LEVELS, PATH, makeQuestion } from '../maths/questions';
import { seededRng } from '../maths/random';
import { CLIPS, clipIds, wording } from './catalogue';

const path = (p: string) => fileURLToPath(new URL(p, import.meta.url));
const first = JSON.parse(readFileSync(path('../../../audio/voice.json'), 'utf8')) as Record<string, [number, number]>;
const recordedLater = (key: string) => existsSync(path(`../../voice/clips/${createHash('sha1').update(key).digest('hex').slice(0, 16)}.mp3`));
/** Clips that could not be recorded yet. They are silent in the app and listed in docs/status.md. */
const allowedMissing = new Set(JSON.parse(readFileSync(path('../../voice/missing.json'), 'utf8')) as string[]);

describe('the clip catalogue', () => {
  it('gives every clip its own id and its own recording', () => {
    expect(new Set(CLIPS.map((c) => c.id)).size).toBe(CLIPS.length);
    expect(new Set(CLIPS.map((c) => c.key)).size).toBe(CLIPS.length);
  });

  it('has a recording for every clip: nothing the app says is silent', () => {
    const silent = CLIPS.filter((c) => !first[c.key] && !recordedLater(c.key) && !allowedMissing.has(c.key)).map((c) => c.text);
    // To record them: npm run voice:todo, then tools/voice/record.py (see app/README.md).
    expect(silent).toEqual([]);
  });

  it('has nothing on the missing list that has a recording by now', () => {
    expect([...allowedMissing].filter((k) => first[k] || recordedLater(k))).toEqual([]);
  });

  it('never says "the puppy" or "he": she is Oreo', () => {
    expect(CLIPS.filter((c) => /\bpuppy\b|\b[Hh]e\b/.test(c.text)).map((c) => c.text)).toEqual([]);
  });

  it('matches the script file the recording and the packs are made from', async () => {
    // Update with: npx vitest run src/speech -u
    const clips = CLIPS.map(({ id, text, key, fragment, pack }) => ({ id, text, key, fragment, pack }));
    await expect(JSON.stringify({ clips }, null, 1) + '\n').toMatchFileSnapshot('../../voice/script.json');
  });

  it('matches the script written out for reading', async () => {
    const lines = ['# Voice script', '', 'Everything the app can say, written from `app/voice/script.json`. Do not edit this file: change the wording in `app/src/speech/` and run `npx vitest run src/speech -u` in `app/`.', ''];
    const packs = [...new Set(CLIPS.map((c) => c.pack))];
    for (const pack of packs) {
      const mine = CLIPS.filter((c) => c.pack === pack && !c.id.startsWith('num.'));
      lines.push(`## Pack: ${pack}`, '', `${CLIPS.filter((c) => c.pack === pack).length} clips.`, '');
      const whole = mine.filter((c) => !c.fragment && !/\.\d+$|\.\d+\./.test(c.id) && !/\.(tens|ones|up|down)/.test(c.id));
      const families = new Map<string, string[]>();
      for (const c of mine) if (!whole.includes(c) && !c.fragment) families.set(c.id.split('.')[0]!, [...(families.get(c.id.split('.')[0]!) ?? []), c.text]);
      if (whole.length) lines.push('Whole sentences:', '', ...whole.map((c) => `- ${c.text}`), '');
      if (families.size) lines.push('Sentences with a number, one clip for each number:', '', ...[...families].map(([, texts]) => `- ${texts[0]} (${texts.length} clips)`), '');
      const frags = mine.filter((c) => c.fragment);
      if (frags.length) lines.push('Joining pieces for sums, said with number clips:', '', ...frags.map((c) => `- ${c.text}`), '');
    }
    lines.push('## Numbers', '', '0 to 100, each recorded twice: once for the middle of a sentence and once for its end.', '');
    await expect(lines.join('\n')).toMatchFileSnapshot('../../../docs/voice-script.md');
  });
});

describe('clipIds', () => {
  it('takes ids, present wording and numbers', () => {
    expect(clipIds(['try-again'])).toEqual(['try-again']);
    expect(clipIds(['Try again.'])).toEqual(['try-again']);
    expect(clipIds(['47 is 4 tens and 7 ones.'])).toEqual(['isTO.47']);
  });

  it('says a number one way inside a sentence and another way at its end', () => {
    expect(clipIds([47, 'plus', 10, 'is', 57])).toEqual(['num.47.mid', 'frag.plus', 'num.10.mid', 'frag.is', 'num.57.end']);
    expect(clipIds([47, 'take away', 10, 'is', 37, 'Only the tens change.'])[4]).toBe('num.37.end');
    expect(clipIds(['She has', 7, 'how-many-more-does-he-need'])[1]).toBe('num.7.end');
  });

  it('refuses anything that has no recording', () => {
    expect(() => clipIds(['Hello there.'])).toThrow(/No recorded clip/);
    expect(() => clipIds([101])).toThrow(/No recorded clip/);
  });

  it('gives the words back for the screen', () => {
    expect(wording('try-again')).toBe('Try again.');
    expect(wording(47)).toBe('47');
  });

  it('has a clip for everything the question makers want said', () => {
    const rng = seededRng(3);
    for (const id of PATH) {
      for (let level = 1; level <= LEVELS[id]; level++) {
        for (let i = 0; i < 3000; i++) {
          const q = makeQuestion(id, level, rng) as { say?: (string | number)[]; sayEq?: (string | number)[]; hint?: string };
          if (q.say) clipIds(q.say);
          if (q.sayEq) clipIds(q.sayEq);
          if (q.hint) clipIds([q.hint]);
        }
      }
    }
  });
});
